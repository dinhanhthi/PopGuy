    private static LibraryPreset OpenUrl(
        string id, LibraryCategory category, string title, string icon, string url, string description) =>
        new(id, category, () => new CustomAction
        {
            Title = title,
            ActionDescription = description,
            Icon = ActionIcon.SfSymbol(icon),
            Type = CustomActionType.OpenUrl,
            SystemPrompt = "",
            ScriptSource = url,
            AfterRun = AfterRunBehavior.CloseToolbar,
        });
